nodes, edges = [], []

def card(id, col, lane, row, color, title, text, task=None, h=200):
    y0 = LANES[lane][0] + 60 + row * 240
    body = f"### {title}\n{text}"
    if task:
        body += f"\n\n🎯 *{task}*"
    nodes.append({"id": id, "type": "text", "text": body, "x": col * COL + 40,
                  "y": y0, "width": W, "height": h, "color": color})

def edge(a, b, label=None, fs="bottom", ts="top", color=None):
    e = {"id": f"{a}-{b}", "fromNode": a, "fromSide": fs, "toNode": b, "toSide": ts}
    if label: e["label"] = label
    if color: e["color"] = color
    edges.append(e)

